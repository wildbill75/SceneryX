let currentLang = 'en';

function t(key, fallback = '') {
    if (typeof LOCALES !== 'undefined') {
        if (LOCALES[currentLang] && LOCALES[currentLang][key] !== undefined) {
            return LOCALES[currentLang][key];
        }
        if (LOCALES['en'] && LOCALES['en'][key] !== undefined) {
            return LOCALES['en'][key];
        }
    }
    return fallback || key;
}

function getLocalizedCountryName(isoUpper, defaultName = '') {
    if (!isoUpper) return defaultName;
    const iso = isoUpper.toUpperCase().trim();
    if (currentLang !== 'en' && LOCALIZED_COUNTRIES[currentLang] && LOCALIZED_COUNTRIES[currentLang][iso]) {
        return LOCALIZED_COUNTRIES[currentLang][iso];
    }
    if (typeof ISO_TO_COUNTRY_NAME !== 'undefined' && ISO_TO_COUNTRY_NAME[iso]) {
        return ISO_TO_COUNTRY_NAME[iso];
    }
    return defaultName || iso;
}

function getLocalizedAirportType(rawType) {
    if (!rawType) return t('filter.type_regional', 'Regional');
    const s = rawType.toLowerCase();
    if (s.includes('international') || s.includes('internacional')) return t('filter.type_international', 'International');
    if (s.includes('regional')) return t('filter.type_regional', 'Regional');
    if (s.includes('general') || s.includes('ga') || s.includes('aviación') || s.includes('aviacion')) return t('filter.type_ga', 'General Aviation');
    if (s.includes('heli') || s.includes('water') || s.includes('wasser') || s.includes('hidro')) return t('filter.type_heli_water', 'Heli / Water');
    return rawType;
}

function setAppLanguage(lang) {
    if (!LOCALES[lang]) lang = 'en';
    currentLang = lang;
    if (typeof currentSettings !== 'undefined' && currentSettings) {
        currentSettings.language = lang;
    }

    // Apply data-i18n to elements
    document.querySelectorAll('[data-i18n]').forEach(el => {
        const k = el.getAttribute('data-i18n');
        if (k) el.innerText = t(k, el.innerText);
    });

    // Apply data-i18n-title to elements
    document.querySelectorAll('[data-i18n-title]').forEach(el => {
        const k = el.getAttribute('data-i18n-title');
        if (k) el.setAttribute('title', t(k, el.getAttribute('title') || ''));
    });

    // Apply data-i18n-placeholder to inputs
    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
        const k = el.getAttribute('data-i18n-placeholder');
        if (k) el.setAttribute('placeholder', t(k, el.getAttribute('placeholder') || ''));
    });

    // Update Language select if present in Settings modal
    const langSelect = document.getElementById('cfg-app-language');
    if (langSelect && langSelect.value !== lang) {
        langSelect.value = lang;
    }

    // Refresh dynamic stats banner if present
    if (typeof updateInvestmentBannerUI === 'function') {
        updateInvestmentBannerUI();
    }

    // Refresh star rating filter display in left sidebar
    if (typeof renderFilterStarWidget === 'function' && typeof minStarFilter !== 'undefined') {
        renderFilterStarWidget(minStarFilter);
    }

    // Refresh right detail drawer if currently open in Airport Mode
    if (typeof activeDrawerMode !== 'undefined' && activeDrawerMode === 'AIRPORT' && typeof selectedAirport !== 'undefined' && selectedAirport && typeof showAirportDetails === 'function') {
        showAirportDetails(selectedAirport);
    }

    // Refresh right detail drawer if currently open in Country Mode
    if (typeof activeDrawerMode !== 'undefined' && activeDrawerMode === 'COUNTRY' && typeof selectedCountryCode !== 'undefined' && selectedCountryCode && typeof openCountryDrawer === 'function') {
        openCountryDrawer(selectedCountryCode, selectedCountryName);
    }

    // Refresh conflict resolution modal if currently open
    const conflictModal = document.getElementById('conflict-resolution-modal');
    if (conflictModal && !conflictModal.classList.contains('hidden') && typeof renderConflictModalStep === 'function' && typeof currentConflictIndex !== 'undefined') {
        renderConflictModalStep(currentConflictIndex);
    }

    // Refresh flight planning banner if active
    if (typeof updateFlightPlanningBannerUI === "function") {
        updateFlightPlanningBannerUI();
    }
}
